    def install
      venv = virtualenv_create(libexec, "python3.14")
      venv.pip_install resources
      system libexec/"bin/python", "-m", "pip", "install",
             "--disable-pip-version-check", "playwright==1.64.1",
             # wheel: its sdist needs uv_build, which needs Rust
             "textual-image==0.14.2"
      venv.pip_install_and_link buildpath
    end

    def caveats
      <<~EOS
        artwork-tui renders via Chromium. Download it once with:
          #{opt_libexec}/bin/playwright install chromium
      EOS
    end

